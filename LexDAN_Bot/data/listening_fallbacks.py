def _generic_script(tid: str, title: str, setting: str) -> list[tuple[int, str]]:
    """12 реплик с уникальными деталями по id темы (если нет готового скрипта)."""
    s = _h(tid)
    prices = [
        "three pounds",
        "four pounds fifty",
        "six pounds",
        "eight pounds twenty",
        "twelve pounds",
        "fifteen pounds",
        "twenty pounds",
        "twenty-eight pounds",
    ]
    times = ["nine", "ten thirty", "eleven", "two o'clock", "three fifteen", "four", "five thirty", "seven"]
    colors = ["blue", "green", "black", "red", "grey", "yellow"]
    places = ["Park Road", "Hill Street", "King Street", "Oak Avenue", "Market Square", "Station Road"]
    nums = ["seven", "twelve", "fourteen", "seventeen", "twenty", "thirty-five", "forty", "fifty"]
    price = prices[s % len(prices)]
    time_a = times[s % len(times)]
    time_b = times[(s // 3) % len(times)]
    color = colors[s % len(colors)]
    place = places[(s // 5) % len(places)]
    num = nums[(s // 7) % len(nums)]
    room = str(100 + (s % 80))
    return [
        (0, f"Thanks for coming. Let's talk about {title}."),
        (1, f"Sure. I came because of {setting}."),
        (0, f"First detail — please note the time: we start at {time_a}."),
        (1, f"Got it. And the place is on {place}, right?"),
        (0, f"Yes, {place}. Look for the {color} sign by the door."),
        (1, f"How much will it cost roughly?"),
        (0, f"Around {price}. Number on the form is {num}."),
        (1, f"Okay. Is room {room} free for us?"),
        (0, f"Room {room} until {time_b}. Bring your ID card."),
        (1, f"I'll arrive ten minutes early. Any other number to remember?"),
        (0, f"Call extension {num} if you're late."),
        (1, f"Perfect. See you at {time_a} on {place}!"),
    ]


