def get_fallback_turns(topic: dict, n0: str, n1: str) -> list[tuple[str, str]]:
    tid = str(topic.get("id") or "")
    title = str(topic.get("title_en") or topic.get("title_ru") or "this topic")
    setting = str(topic.get("setting") or title)
    raw = _SCRIPTS.get(tid) or _generic_script(tid, title, setting)
    out: list[tuple[str, str]] = []
    for idx, text in raw[:12]:
        sp = n0 if int(idx) == 0 else n1
        t = text.replace("{n0}", n0).replace("{n1}", n1)
        out.append((sp, t))
    while len(out) < 12:
        sp = n0 if len(out) % 2 == 0 else n1
        out.append((sp, f"Okay, let's continue with {title}."))
    return out[:12]
